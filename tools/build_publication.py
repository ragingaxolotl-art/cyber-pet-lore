"""Maintained additions and generated archive counts, without invented dates."""
from pathlib import Path
import json,re
ROOT=Path(__file__).resolve().parents[1];SITE=ROOT/'site'
def build():
 records=json.loads((ROOT/'sources/publication-manifest.json').read_text())
 ids=set()
 for r in records:
  assert r['id'] not in ids and re.fullmatch(r'\d{4}-\d{2}-\d{2}',r['date']);ids.add(r['id'])
  assert (SITE/r['url'].split('#')[0].split('?')[0]).exists(),r['url']
 (SITE/'creation-log.json').write_text(json.dumps(records,ensure_ascii=False,indent=2)+'\n')
 catalog=json.loads((SITE/'catalog.json').read_text());wiki=json.loads((SITE/'wiki.json').read_text());search=json.loads((SITE/'search-index.json').read_text())
 coverage=json.loads((ROOT/'sources/publication-coverage.json').read_text())
 known=set(coverage['readingIds']);unrecorded=[e['id'] for e in catalog['entries'] if e['id'] not in known]
 if unrecorded:print('PUBLICATION WARNING: add release notes for new readings:',', '.join(unrecorded))
 (SITE/'publication-report.json').write_text(json.dumps(dict(unrecordedReadingIds=unrecorded,release=coverage['release']),indent=2)+'\n')
 counts=dict(readings=len(catalog['entries']),topics=len(wiki['topics']),passages=search['passageCount'],collections=catalog['counts'])
 (SITE/'archive-stats.json').write_text(json.dumps(counts,indent=2)+'\n')
 p=ROOT/'README.md';text=p.read_text();summary='<!-- archive-counts:start -->\n'+f"{counts['readings']:,} indexed readings, {counts['topics']:,} knowledge topics, and {counts['passages']:,} searchable passages. Counts are generated by the catalog build.\n\n"+' · '.join(f'{k}: {v}' for k,v in counts['collections'].items())+'\n<!-- archive-counts:end -->'
 text=re.sub(r'<!-- archive-counts:start -->.*?<!-- archive-counts:end -->',lambda m:summary,text,flags=re.S);p.write_text(text)
if __name__=='__main__':build()
